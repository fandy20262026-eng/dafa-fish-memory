export const SKILL_NAME = 'memory-usage'

export const SKILL_DESCRIPTION = '什么时候该往长期记忆里写、怎么写、检索结果怎么用：'
  + '区分「用户原话」与「我的推断」，纠正与删除前先确认。'

export const SKILL_BODY = `# 本地记忆使用规则

## 什么时候写

只在三种情况下调用 \`memory_write\`：

1. 用户**明确要求**记住（「记住」「记一下」「以后都这样」）。
2. 用户给出**长期偏好或约束**（回答风格、命名习惯、禁止项、必须项）。
3. 用户**敲定了一个决定**，且这个决定会影响以后的做法（技术选型、流程、分工）。

不要写：临时的任务进度、一次性调试结论、已经写在文件里的内容、聊天摘要。

## 怎么写

- 用**用户的原话**，或紧贴原话的精炼句子；不要替用户扩写。
- 字面值照抄：路径、端口、版本号、账号、阈值，一个字符都不要改。
- 一条只讲一件事。宁可写三条短的，不要写一条包罗万象的。

## 检索结果怎么用

\`memory_search\` 每条结果都带 \`basis\`：

| basis | 含义 | 怎么用 |
|---|---|---|
| \`direct_report\` | 用户本人说过的话 | 可以引用，可以说「你之前说过」 |
| \`derived_summary\` | 我自己总结的 | 只能说「我记下的结论是」，**不能说成用户原话** |

记忆**可能过期**。涉及当前状态（版本、配置、谁在用什么）时，先验证再断言。

## 与 skill 冲突时：以 skill 为准

**skill 是权威，记忆是参考。**

| 维度 | skill | 记忆 |
|---|---|---|
| 装什么 | 程序性知识（怎么做：步骤、命令、字段陷阱） | 事实与偏好（用哪个账号、你偏好什么、为什么改过方案） |
| 谁写的 | 人写的，稳定 | 从对话里抽的，会变 |
| 冲突时 | **照 skill 做** | 让位 |

具体规矩：

- skill 规定了流程，就不要因为「记忆里提过另一种做法」而跳过 skill 的步骤。
- 记忆里的**流程类内容**（触发 → 做法 → 验证 那种）**默认不参与自动注入**，只在显式 \`memory_search\` 时出现——这是为了让 skill 保持唯一权威。
- 记忆可以用来补充**这次的具体情况**：「skill 说用同步脚本，而记忆里记着昨天 Tushare 502 所以换了备用源」，这类补充是有价值的；但**不能替代 skill 里的步骤**。
- 拿不准时，先按 skill 做，再回头问用户记忆里的说法是否还成立。

## 纠正与删除

\`memory_forget\` 会核对用户**最新一条消息**：里面要有「删掉/忘掉/改成」这类词，并且指明目标（id 或关键词）。否则会被拒绝。

被拒绝时不要换个说法重试——直接告诉用户「需要你明确说要删哪一条」。

删除前先说清后果：原文仍保留在本地库中，只是不再参与召回。
`
